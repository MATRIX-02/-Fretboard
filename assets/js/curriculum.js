const CURRICULUM = {
  phases: PHASES,
  weeks: WEEKS,
  totalWeeks: WEEKS.length,
  week(n) { return WEEKS.find((w) => w.n === n); },
  phase(id) { return PHASES.find((p) => p.id === id); },
  phaseOf(n) { return PHASES.find((p) => n >= p.weeks[0] && n <= p.weeks[1]); },
  weeksIn(id) { return WEEKS.filter((w) => w.phase === id); },
  minutes(week, mode) {
    const maxTier = mode === "short" ? 1 : mode === "long" ? 3 : 2;
    return week.blocks.filter((b) => b.tier <= maxTier).reduce((s, b) => s + b.min, 0);
  },
  blocksFor(week, mode) {
    const maxTier = mode === "short" ? 1 : mode === "long" ? 3 : 2;
    return week.blocks.filter((b) => b.tier <= maxTier);
  },
};

